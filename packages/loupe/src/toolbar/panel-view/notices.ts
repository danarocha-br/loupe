// The notices (PER-133, PER-179, PER-184, PER-227): components whose source changed
// since the last `loupe generate`, components on the page it has never read, a Product
// layer in another format, one that went missing, and Overrides off. Regeneration stays
// explicit (PER-100 §5), so each notice names the command and runs nothing. Amber for
// what may be out of date, red for what stops Loupe working.

import { formatNotice, missingLayerAdvice } from "../../format-notice.js";
import type { LayerStatus } from "../../layer-status.js";
import { plural } from "../format.js";
import type { NoticeView } from "./types.js";
import { OVERRIDES_OFF_TITLE, overridesOffBanner } from "./words.js";

const RUN_BELOW = "Run the command below from the repo root.";

/** "1 component", "2 components": what a notice counts at its head's right. */
const components = (count: number) => plural(count, "component");

/** What `status` says about the Product layer, or nothing while it reads as `generate` left it. */
export function layerNotice(status: LayerStatus | null): NoticeView | null {
  if (status === null) return null;
  // The loader hands files back untouched while the file is gone, so Instances leave the
  // panel as their modules reload; this says why. It still depends on the file then, so
  // they come back by themselves once it does.
  if (status.missing) {
    return {
      kind: "missing",
      tone: "alert",
      title: "Product layer missing",
      meta: null,
      body: `adapt-list.json is gone, so files that reload lose their Adapters and their Instances drop out of this panel. A branch switch can remove it. ${missingLayerAdvice(status.command, "the command below")}`,
      rows: [],
      command: status.command,
    };
  }
  if (status.format !== null) {
    const { layer, runtime, newer } = status.format;
    return {
      kind: "format",
      tone: "alert",
      title: `Generated by ${newer ? "a newer" : "an older"} Loupe`,
      meta: `Format ${layer ?? "?"} ≠ ${runtime}`,
      body: formatNotice(status.format),
      rows: [],
      command: status.command,
    };
  }
  if (status.stale.length === 0) return null;
  const count = staleCount(status);
  return {
    kind: "stale",
    tone: "amber",
    title: "Source changed",
    meta: components(count),
    body: `${components(count)} changed since the last generate. Their props here may be out of date. ${RUN_BELOW}`,
    rows: status.stale.map((module) => ({
      text: module.components.join(", ") || "No components",
      value: module.source.split("/").slice(-2).join("/"),
      valueTitle: module.changed.join("\n"),
    })),
    command: status.command,
  };
}

/** The components on this page `generate` has never read: none, no notice. */
export function notGeneratedNotice(names: readonly string[], command: string): NoticeView | null {
  if (names.length === 0) return null;
  const one = names.length === 1;
  return {
    kind: "not-generated",
    tone: "amber",
    title: "Not generated yet",
    meta: components(names.length),
    body: `${components(names.length)} on this page ${one ? "is" : "are"} not generated yet, so ${one ? "it has" : "they have"} no prop metadata and no Adapter. ${RUN_BELOW}`,
    rows: [{ text: names.join(", "), value: null, valueTitle: null }],
    command,
  };
}

/** The React self-check failed (PER-184): said once, across the panel, not again on the Instance. */
export function overridesOffNotice(reason: string): NoticeView {
  return { kind: "overrides-off", tone: "alert", title: OVERRIDES_OFF_TITLE, meta: null, body: overridesOffBanner(reason), rows: [], command: null };
}

/**
 * What the notices say, for the panel's live regions (review 2026-11-20): the cards come
 * and go with the view, so they carry no role. A missing or other-format layer is an
 * alert; changed sources and Overrides off a status. Each is said in its notice's words.
 */
export function noticesSaid(layer: NoticeView | null, overridesOff: NoticeView | null): { alert: string; status: string } {
  const said = { alert: "", status: [] as string[] };
  if (layer?.kind === "missing") said.alert = `${layer.title}: adapt-list.json is gone, so Instances may drop out of this panel.`;
  else if (layer?.kind === "format") said.alert = `${layer.title}. ${layer.body}`;
  else if (layer?.kind === "stale") said.status.push(`${layer.title}: ${layer.meta} changed since the last generate.`);
  if (overridesOff) said.status.push(`${overridesOff.title}. ${overridesOff.body}`);
  return { alert: said.alert, status: said.status.join(" ") };
}

function staleCount(status: LayerStatus): number {
  return status.stale.reduce((sum, module) => sum + module.components.length, 0);
}
