// The page as `panelView()` reads it: every Instance on it, grouped by component,
// the records, the components seen earlier on this route, and what the Product
// layer says about them. Read once per call.

import { callSiteLabels } from "../../call-site.js";
import type { LayerStatus } from "../../layer-status.js";
import type { InstanceRow, LoupeDebug, RecordRow } from "../../runtime/debug.js";
import { currentRoute, type LastSeen, registry } from "../../runtime/registry.js";
import type { Status } from "../../runtime/store.js";
import type { SeenComponents } from "./types.js";

/** An Instance that isn't mounted but still holds an Instance-scope record: listed as "No Instance mounted". */
export type HeldInstance = {
  id: string;
  record: RecordRow;
  /** How it last rendered; null when it unmounted before the registry kept track. */
  lastSeen: LastSeen | null;
};

export type ComponentGroup = {
  component: string;
  /** Mounted Instances. */
  instances: InstanceRow[];
  /** Unmounted Instances that still hold something (PER-136); one that holds nothing isn't listed. */
  held: HeldInstance[];
  /** Override values on its mounted and held Instances. */
  overrides: number;
};

export type Page = {
  status: Status;
  route: string;
  /** Every Instance on the page: adapted, browser-rendered with no Adapter, and server-rendered. */
  rows: InstanceRow[];
  groups: ComponentGroup[];
  /** Components seen earlier on this page with no Instance mounted now, such as a closed menu's. */
  interaction: string[];
  records: RecordRow[];
  /** Override values across every record. */
  overrideCount: number;
  /** Mounted Instances, for the list's summary. */
  instanceCount: number;
  seen: SeenComponents;
  /** Components `generate` hasn't read yet, and components whose source changed since it did. */
  notGenerated: ReadonlySet<string>;
  stale: ReadonlySet<string>;
  /** The command that rewrites the Product layer; empty while it can't be read. */
  command: string;
};

export function readPage(debug: LoupeDebug, seen: SeenComponents, layer: LayerStatus | null): Page {
  const route = currentRoute();
  const rows = debug.list();
  const components = new Set(seen.route === route ? seen.components : []);
  const byComponent = new Map<string, InstanceRow[]>();
  for (const row of rows) {
    byComponent.set(row.component, [...(byComponent.get(row.component) ?? []), row]);
    components.add(row.component);
  }
  const records = debug.records();
  const held = heldInstances(debug, records, route);
  const listed = new Set([...byComponent.keys(), ...held.keys()]);
  const groups = [...listed]
    .map((component): ComponentGroup => {
      const instances = byComponent.get(component) ?? [];
      const heldHere = held.get(component) ?? [];
      return {
        component,
        instances,
        held: heldHere,
        overrides:
          instances.reduce((sum, row) => sum + Object.keys(row.overrides).length, 0) +
          heldHere.reduce((sum, entry) => sum + Object.keys(entry.record.values).length, 0),
      };
    })
    .sort((a, b) => a.component.localeCompare(b.component));
  return {
    status: registry().store.status,
    route,
    rows,
    groups,
    interaction: [...components].filter((component) => !listed.has(component)).sort(),
    records,
    overrideCount: records.reduce((sum, record) => sum + Object.keys(record.values).length, 0),
    instanceCount: groups.reduce((sum, group) => sum + group.instances.length, 0),
    seen: { route, components },
    notGenerated: new Set(notGeneratedComponents(layer, groups)),
    stale: staleComponents(layer),
    command: layer?.command ?? "",
  };
}

/** Component names whose module's source changed since the last `generate`. */
function staleComponents(layer: LayerStatus | null): Set<string> {
  return new Set(layer?.stale.flatMap((module) => module.components) ?? []);
}

/**
 * Components on the page that the next `generate` would add. Matched by name, like
 * the stale flag, since an Instance doesn't know its module. An adapted one was
 * generated by definition, and none is flagged while the Product layer can't be
 * read, is missing or is in another format.
 */
function notGeneratedComponents(layer: LayerStatus | null, groups: readonly ComponentGroup[]): string[] {
  if (!layer?.notGenerated) return [];
  const added = new Set(layer.notGenerated);
  return groups
    .filter((group) => group.instances.length > 0 && added.has(group.component) && group.instances.every((row) => !row.adapted))
    .map((group) => group.component);
}

/**
 * Unmounted Instances with an Instance-scope record, by component, on this route
 * only: a record for an Instance on another page is listed there.
 */
function heldInstances(debug: LoupeDebug, records: RecordRow[], route: string): Map<string, HeldInstance[]> {
  const held = new Map<string, HeldInstance[]>();
  for (const record of records) {
    if (record.target.scope !== "instance" || record.mounted.length > 0) continue;
    if (Object.keys(record.values).length === 0) continue;
    const id = record.target.id;
    const lastSeen = debug.lastSeen(id);
    if (lastSeen && lastSeen.route !== route) continue;
    const component = lastSeen?.component ?? callSiteLabels(id).component;
    held.set(component, [...(held.get(component) ?? []), { id, record, lastSeen }]);
  }
  return held;
}

/** The record holding an Instance-scope Override for this id, whether it applies or is held for review. */
export function instanceRecord(records: readonly RecordRow[], id: string): RecordRow | null {
  return records.find((record) => record.target.scope === "instance" && record.target.id === id) ?? null;
}
