// The Product layer's notices (PER-133): components whose source changed since
// the last `loupe generate`, components on the page it has never read (PER-179),
// a Product layer in another format, and one that went missing (PER-227).
// Regeneration stays explicit (PER-100 §5), so each notice names the command and
// runs nothing. Amber for the first two, red for the format and the missing layer,
// below the page or Instance card (PER-140).

import { useCallback, useEffect, useRef, useState } from "react";
import { Command } from "./command.js";
import { Dot } from "./ui/index.js";
import type { LayerStatus } from "../layer-status.js";
import { formatNotice, missingLayerAdvice } from "../format-notice.js";
import { readProductLayerStatus } from "./layer-server.js";
import { warnOnce } from "./warn-once.js";

/** At most one check this often while the page keeps changing; each one stats the sources. */
const MIN_INTERVAL_MS = 2000;

/**
 * The Product layer's status, checked when the panel opens, when the window gets
 * focus back (from the editor, typically) and after the page changes.
 */
export function useLayerStatus(version: number): LayerStatus | null {
  const [status, setStatus] = useState<LayerStatus | null>(null);
  const last = useRef(0);
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);
  // Reads only refs and the state setter, so one closure serves every render.
  const check = useCallback(() => {
    if (timer.current !== null) return;
    const wait = Math.max(0, last.current + MIN_INTERVAL_MS - Date.now());
    timer.current = setTimeout(() => {
      timer.current = null;
      last.current = Date.now();
      readProductLayerStatus().then(
        (next) => setStatus((previous) => (JSON.stringify(previous) === JSON.stringify(next) ? previous : next)),
        // A restarting dev server refuses the call; the next check tries again.
        (error: unknown) => warnOnce(`[loupe] Couldn't read the Product layer's status: ${String(error)}`),
      );
    }, wait);
  }, []);
  useEffect(() => {
    const onFocus = () => check();
    const onVisible = () => document.visibilityState === "visible" && check();
    window.addEventListener("focus", onFocus);
    document.addEventListener("visibilitychange", onVisible);
    return () => {
      window.removeEventListener("focus", onFocus);
      document.removeEventListener("visibilitychange", onVisible);
      if (timer.current !== null) clearTimeout(timer.current);
      timer.current = null;
    };
  }, [check]);
  // A new page version is the trigger; the check reads nothing from it.
  useEffect(() => check(), [check, version]);
  useEffect(() => {
    if (status?.format == null) return;
    warnOnce(`[loupe] ${formatNotice(status.format)} ${status.command}`, console.error);
  }, [status]);
  return status;
}

export function NotGeneratedNotice({ names, command }: { names: readonly string[]; command: string }) {
  if (names.length === 0) return null;
  const one = names.length === 1;
  return (
    <div className="card notice-card" data-testid="not-generated-notice">
      <div className="head">
        <div className="title">
          <Dot tone="amber" />
          Not generated yet
        </div>
        <span className="meta">
          {names.length} component{one ? "" : "s"}
        </span>
      </div>
      <p className="body">
        {names.length} component{one ? "" : "s"} on this page {one ? "is" : "are"} not generated yet, so{" "}
        {one ? "it has" : "they have"} no prop metadata and no Adapter.
        Run the command below from the repo root.
      </p>
      <ul>
        <li>{names.join(", ")}</li>
      </ul>
      <Command text={command} />
    </div>
  );
}

/**
 * What the Product layer's notice says, for the panel's live regions (review 2026-11-20):
 * the cards come and go with the view, so they carry no role; a missing or other-format
 * layer is an alert, changed sources a status.
 */
export function layerAnnouncement(status: LayerStatus | null): { alert: string; status: string } {
  if (status === null) return { alert: "", status: "" };
  if (status.missing) return { alert: "Product layer missing: adapt-list.json is gone, so Instances may drop out of this panel.", status: "" };
  if (status.format !== null) {
    return { alert: `Generated by ${status.format.newer ? "a newer" : "an older"} Loupe. ${formatNotice(status.format)}`, status: "" };
  }
  const count = status.stale.reduce((sum, module) => sum + module.components.length, 0);
  return { alert: "", status: count === 0 ? "" : `Source changed: ${count} component${count === 1 ? "" : "s"} changed since the last generate.` };
}

export function LayerNotices({ status }: { status: LayerStatus | null }) {
  if (status === null) return null;
  // The loader hands files back untouched while the file is gone, so Instances leave the
  // panel as their modules reload; this says why. It still depends on the file then, so
  // they come back by themselves once it does.
  if (status.missing) {
    return (
      <div className="card notice-card" data-testid="missing-notice">
        <div className="head">
          <div className="title">
            <Dot tone="alert" />
            Product layer missing
          </div>
        </div>
        <p className="body">
          adapt-list.json is gone, so files that reload lose their Adapters and their Instances drop out of this panel. A
          branch switch can remove it. {missingLayerAdvice(status.command, "the command below")}
        </p>
        <Command text={status.command} />
      </div>
    );
  }
  if (status.format !== null) {
    const { layer, runtime, newer } = status.format;
    return (
      <div className="card notice-card" data-testid="format-notice">
        <div className="head">
          <div className="title">
            <Dot tone="alert" />
            Generated by {newer ? "a newer" : "an older"} Loupe
          </div>
          <span className="meta">
            Format {layer ?? "?"} ≠ {runtime}
          </span>
        </div>
        <p className="body">{formatNotice(status.format)}</p>
        <Command text={status.command} />
      </div>
    );
  }
  if (status.stale.length === 0) return null;
  const count = status.stale.reduce((sum, module) => sum + module.components.length, 0);
  return (
    <div className="card notice-card" data-testid="stale-notice">
      <div className="head">
        <div className="title">
          <Dot tone="amber" />
          Source changed
        </div>
        <span className="meta">
          {count} component{count === 1 ? "" : "s"}
        </span>
      </div>
      <p className="body">
        {count} component{count === 1 ? "" : "s"} changed since the last generate. Their props here may be out of date.
        Run the command below from the repo root.
      </p>
      <ul>
        {status.stale.map((module) => (
          <li key={module.source}>
            <span>{module.components.join(", ") || "No components"}</span>{" "}
            <span className="mono" title={module.changed.join("\n")}>
              {module.source.split("/").slice(-2).join("/")}
            </span>
          </li>
        ))}
      </ul>
      <Command text={status.command} />
    </div>
  );
}
