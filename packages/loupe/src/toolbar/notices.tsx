// The Product layer's notices (PER-133): components whose source changed since
// the last `loupe generate`, components on the page it has never read (PER-179),
// and a Product layer in another format. Regeneration stays explicit (PER-100 §5),
// so each notice names the command and runs nothing.

import { useCallback, useEffect, useRef, useState } from "react";
import type { LayerStatus } from "../layer-status.js";
import type { ComponentGroup } from "./page.js";
import { formatNotice } from "../format-notice.js";
import { readProductLayerStatus } from "./layer-server.js";

/** At most one check this often while the page keeps changing; each one stats the sources. */
const MIN_INTERVAL_MS = 2000;

/** Logged once per message, so a re-check doesn't repeat it. Lives as long as the page. */
const logged = new Set<string>();

/**
 * The Product layer's status, checked when the panel opens, when the window gets
 * focus back (from the editor, typically) and after the page changes.
 */
export function useLayerStatus(version: number): LayerStatus | null {
  const [status, setStatus] = useState<LayerStatus | null>(null);
  const last = useRef(0);
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);
  // Reads only refs and the state setter, so one closure serves every render.
  const check = useCallback(() => {
    if (timer.current !== null) return;
    const wait = Math.max(0, last.current + MIN_INTERVAL_MS - Date.now());
    timer.current = setTimeout(() => {
      timer.current = null;
      last.current = Date.now();
      readProductLayerStatus().then(
        (next) => setStatus((previous) => (JSON.stringify(previous) === JSON.stringify(next) ? previous : next)),
        // A restarting dev server refuses the call; the next check tries again.
        (error: unknown) => logOnce(`[loupe] Couldn't read the Product layer's status: ${String(error)}`, console.warn),
      );
    }, wait);
  }, []);
  useEffect(() => {
    const onFocus = () => check();
    const onVisible = () => document.visibilityState === "visible" && check();
    window.addEventListener("focus", onFocus);
    document.addEventListener("visibilitychange", onVisible);
    return () => {
      window.removeEventListener("focus", onFocus);
      document.removeEventListener("visibilitychange", onVisible);
      if (timer.current !== null) clearTimeout(timer.current);
      timer.current = null;
    };
  }, [check]);
  // A new page version is the trigger; the check reads nothing from it.
  useEffect(() => check(), [check, version]);
  useEffect(() => {
    if (status?.format == null) return;
    logOnce(`[loupe] ${formatNotice(status.format)} ${status.command}`, console.error);
  }, [status]);
  return status;
}

function logOnce(message: string, log: (message: string) => void): void {
  if (logged.has(message)) return;
  logged.add(message);
  log(message);
}

/** Component names whose module's source changed since the last `generate`. */
export function staleComponents(status: LayerStatus | null): Set<string> {
  return new Set(status?.stale.flatMap((module) => module.components) ?? []);
}

/**
 * Components on the page that `meta/` doesn't name: new since the last `generate`.
 * Matched by name, like the stale flag, since an Instance doesn't know its module.
 * An adapted one was generated by definition, and none is flagged while the
 * Product layer can't be read or is in another format.
 */
export function notGeneratedComponents(status: LayerStatus | null, groups: readonly ComponentGroup[]): string[] {
  if (!status?.generated) return [];
  const known = new Set(status.generated);
  return groups
    .filter(
      (group) =>
        group.instances.length > 0 &&
        !known.has(group.component) &&
        group.instances.every((row) => !row.adapted),
    )
    .map((group) => group.component);
}

export function NotGeneratedNotice({ names, command }: { names: readonly string[]; command: string }) {
  if (names.length === 0) return null;
  const one = names.length === 1;
  return (
    <div className="banner" role="status" data-testid="not-generated-notice">
      <div>
        {names.length} component{one ? "" : "s"} on this page {one ? "is" : "are"} not generated yet, so{" "}
        {one ? "it has" : "they have"} no prop metadata and no Adapter.
      </div>
      <div>{names.join(", ")}</div>
      <div className="mono">{command}</div>
    </div>
  );
}

export function LayerNotices({ status }: { status: LayerStatus | null }) {
  if (status === null) return null;
  if (status.format !== null) {
    return (
      <div className="banner" role="alert" data-testid="format-notice">
        {formatNotice(status.format)}
        <div className="mono">{status.command}</div>
      </div>
    );
  }
  if (status.stale.length === 0) return null;
  const count = status.stale.reduce((sum, module) => sum + module.components.length, 0);
  return (
    <div className="banner" role="status" data-testid="stale-notice">
      <div>
        {count} component{count === 1 ? "" : "s"} changed since the last generate. Their props here may be out of date.
      </div>
      <ul className="list">
        {status.stale.map((module) => (
          <li key={module.source}>
            {module.components.join(", ") || "No components"}{" "}
            <span className="mono muted" title={module.changed.join("\n")}>
              {module.source.split("/").slice(-2).join("/")}
            </span>
          </li>
        ))}
      </ul>
      <div className="mono">{status.command}</div>
    </div>
  );
}
