// The root Biome config: the Product layer excluded from "files.includes",
// under a comment saying why.

// jsonc-parser ships UMD as `main`, which Node can't read named exports from.
import jsonc from "jsonc-parser";
import { indentAt, lineStart } from "../syntax.js";
import { PRODUCT_LAYER, type TouchPoint } from "../touch-points.js";
import { type Candidates, cut, lines, type Range, revertToCandidate } from "./shared.js";

const EXCLUSION = `!${PRODUCT_LAYER.path}`;
/** The comment `apply` writes above the exclusion. */
const BIOME_COMMENT = "// Loupe's Product layer: generated by loupe init and loupe generate.";

/** The touch point in `file`, the root's biome.jsonc or biome.json. */
export function biomeConfig(file: string): TouchPoint {
  const tp: TouchPoint = {
    id: "biome-config",
    role: "excludes-layer",
    file,
    applyByHand: [`In ${file}, add to the "files.includes" array:`, `  "${EXCLUSION}"`],
    revertByHand: `remove "${EXCLUSION}" and the comment above it from "files.includes"`,
    find(text) {
      const includes = includesNode(text);
      const present = includes?.type === "array" && includes.children?.some((c) => c.value === EXCLUSION);
      return present ? { canonical: JSON.stringify(EXCLUSION), exact: true } : undefined;
    },
    apply(text) {
      if (text === undefined) return { unexpected: `${file} doesn't exist.` };
      const errors: jsonc.ParseError[] = [];
      jsonc.parseTree(text, errors, { allowTrailingComma: true });
      if (errors.length > 0) return { unexpected: `${file} doesn't parse.` };
      const includes = includesNode(text);
      const last = includes?.type === "array" ? includes.children?.at(-1) : undefined;
      if (!last) return { unexpected: `"files.includes" in ${file} isn't a non-empty array.` };

      const indent = indentAt(text, last.offset);
      let at = last.offset + last.length;
      const trailingComma = /^\s*,/.exec(text.slice(at));
      const added = [BIOME_COMMENT, `"${EXCLUSION}"`];
      let insertion = added.map((l) => `\n${indent}${l}`).join("");
      if (trailingComma) {
        at += trailingComma[0].length;
        insertion += ",";
      } else insertion = `,${insertion}`;
      return { text: `${text.slice(0, at)}${insertion}${text.slice(at)}`, summary: `excluded ${PRODUCT_LAYER.path}` };
    },
    revert(text) {
      return revertToCandidate(tp, text, candidates(text), `removed the ${EXCLUSION} exclusion`);
    },
  };
  return tp;
}

function includesNode(text: string): jsonc.Node | undefined {
  const tree = jsonc.parseTree(text, [], { allowTrailingComma: true });
  return tree ? jsonc.findNodeAtLocation(tree, ["files", "includes"]) : undefined;
}

function candidates(text: string): Candidates {
  const includes = includesNode(text);
  const items = includes?.type === "array" ? (includes.children ?? []) : [];
  const index = items.findIndex((c) => c.value === EXCLUSION);
  const node = items[index];
  if (!node) return { manual: `"${EXCLUSION}" isn't in "files.includes"` };
  const previous = items[index - 1];
  const prevEnd = previous ? previous.offset + previous.length : undefined;
  const nodeEnd = node.offset + node.length;
  // The fallback takes out the entry's line and Loupe's comment line just above it,
  // never what else sits between, plus the comma that now has nothing after it.
  const trailing = /^[ \t]*,/.exec(text.slice(nodeEnd))?.[0] ?? "";
  const ranges: Range[] = [lines(text, node.offset, nodeEnd + trailing.length)];
  const entryLine = lineStart(text, node.offset);
  const above = entryLine > 0 ? lineStart(text, entryLine - 1) : -1;
  if (above >= 0 && text.slice(above, entryLine - 1).trim() === BIOME_COMMENT) ranges.push([above, entryLine]);
  const comma = prevEnd === undefined || trailing ? -1 : text.indexOf(",", prevEnd);
  if (comma !== -1 && comma < node.offset && /^\s*$/.test(text.slice(prevEnd, comma))) ranges.push([comma, comma + 1]);
  const fallback = cut(text, ranges);
  const candidates: string[] = [];
  if (prevEnd !== undefined) {
    // apply wrote `,<comment><entry>` after the last entry, or `<comment><entry>,` after its trailing comma.
    candidates.push(cut(text, [[prevEnd, nodeEnd]]));
    const before = /^\s*,/.exec(text.slice(prevEnd))?.[0];
    const after = /^\s*,/.exec(text.slice(nodeEnd))?.[0];
    if (before && after) candidates.push(cut(text, [[prevEnd + before.length, nodeEnd + after.length]]));
  }
  return { candidates: [...candidates, fallback], fallback };
}
