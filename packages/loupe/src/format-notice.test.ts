import { describe, expect, it } from "vitest";
import { formatNotice, missingLayerAdvice } from "./format-notice.js";

const COMMAND = "pnpm -C apps/app exec loupe generate --design-system <dir> --app <dir>";

describe("missingLayerAdvice (PER-227)", () => {
  it("puts git first, keeps regenerating for an intact Product layer, and asks for no restart", () => {
    const advice = missingLayerAdvice(COMMAND);
    expect(advice.startsWith("Restore it with git. If the rest of the Product layer is intact, write it again ")).toBe(true);
    // The loader depends on adapt-list.json even while it is gone, so Instances return when the file does.
    expect(advice).not.toMatch(/restart/i);
    expect(advice.endsWith("(. is the app itself).")).toBe(true);
  });

  it("points at the command by itself, or by the reference a card gives it", () => {
    expect(missingLayerAdvice(COMMAND)).toContain(`with ${COMMAND}, replacing`);
    expect(missingLayerAdvice(COMMAND, "the command below")).toContain("with the command below, replacing");
    expect(missingLayerAdvice(COMMAND, "the command below")).not.toContain("pnpm");
  });

  it("says where to run it: the repo root, which `pnpm -C` leaves for the app (PR #58)", () => {
    // Pasted into the terminal `next dev` runs in, often the app folder, `pnpm -C apps/app` finds no folder.
    expect(missingLayerAdvice(COMMAND)).toContain(`write it again from the repo root with ${COMMAND}, replacing`);
    expect(missingLayerAdvice(COMMAND, "the command below")).toContain("write it again from the repo root with the command below, replacing");
  });

  it("says what to put in <dir>: a path from the app folder, not from the repo root", () => {
    expect(missingLayerAdvice(COMMAND)).toContain("replacing each <dir> with a path from the app folder (. is the app itself)");
  });

  it("explains <name> only for a command that asks for the specifier", () => {
    expect(missingLayerAdvice(COMMAND)).not.toContain("<name>");
    const advice = missingLayerAdvice(`${COMMAND} --specifier <name>`, "the command below");
    expect(advice).toContain("and <name> with the path the app imports the Product layer by");
  });
});

describe("formatNotice", () => {
  // The Toolbar's card, its console line and withLoupe's terminal line all put the command after it (PER-233).
  it("ends where the command follows, saying where to run it", () => {
    expect(formatNotice({ layer: 0, runtime: 1, newer: false })).toBe(
      "The Product layer was generated by an older Loupe (formatVersion 0, and this Loupe reads 1). Regenerate it from the repo root:",
    );
    expect(formatNotice({ layer: 2, runtime: 1, newer: true })).toBe(
      "The Product layer was generated by a newer Loupe (formatVersion 2, and this Loupe reads 1). " +
        "Upgrade @danarocha/loupe to the version that wrote it, or regenerate it with this one from the repo root:",
    );
  });

  it("says unknown for a layer whose format can't be read", () => {
    expect(formatNotice({ layer: null, runtime: 1, newer: false })).toContain("(formatVersion unknown, and this Loupe reads 1)");
  });
});
